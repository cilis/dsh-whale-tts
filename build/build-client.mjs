/**
 * Build the browser half.
 *
 * DSH outside its own repository has no `clientBundle` preset, so the package
 * builds its own lazy-CJS factory: the bundle registers `dsh-whale-tts` with
 * `window.__ModuleLoader__` and resolves `react` from the host module table.
 *
 * The bundler is Rollup + Sucrase (both pure JavaScript). Native esbuild is not
 * usable here: it is a spawned child process, and restricted sandboxes refuse
 * to spawn binaries. Type checking stays in `tsc -p tsconfig.client.json`.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { rollup } from 'rollup'
import sucrase from '@rollup/plugin-sucrase'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = resolve(root, 'lib/client.js')

const EXTERNALS = [
  'react',
  'react-dom',
  'react/jsx-runtime',
  'react/jsx-dev-runtime',
]

const bundle = await rollup({
  input: resolve(root, 'src/client/index.tsx'),
  external: (id) => EXTERNALS.includes(id) || id.startsWith('@deepseek-ai/'),
  plugins: [
    sucrase({
      transforms: ['typescript', 'jsx'],
      jsxPragma: 'React.createElement',
      jsxFragmentPragma: 'React.Fragment',
    }),
  ],
  onwarn(warning, warn) {
    if (warning.code === 'CIRCULAR_DEPENDENCY') return
    warn(warning)
  },
})

const { output } = await bundle.generate({
  format: 'cjs',
  exports: 'named',
  sourcemap: false,
  inlineDynamicImports: true,
  generatedCode: 'es2015',
})

const bundled = output
  .map((chunk) => ('code' in chunk ? chunk.code : ''))
  .join('\n')
if (bundled.trim() === '') throw new Error('client bundle is empty')

const indented = bundled
  .split('\n')
  .map((line) => (line === '' ? line : `    ${line}`))
  .join('\n')

const wrapped =
  '/* dsh-whale-tts browser half — generated by build/build-client.mjs; do not edit. */\n' +
  'window.__ModuleLoader__.load({\n' +
  "  id: 'dsh-whale-tts',\n" +
  '  factory: (require) => {\n' +
  '    var module = { exports: {} };\n' +
  '    var exports = module.exports;\n' +
  `${indented}\n` +
  '    return module.exports;\n' +
  '  },\n' +
  '});\n'

await mkdir(dirname(outFile), { recursive: true })
await writeFile(outFile, wrapped, 'utf8')

await writeFile(
  resolve(root, 'lib/client.d.ts'),
  [
    'export declare const name: string',
    'export declare const inject: readonly string[]',
    'export declare function apply(ctx: unknown): void',
    '',
  ].join('\n'),
  'utf8',
)

console.log(`client bundle written: ${outFile} (${wrapped.length} bytes)`)
